/**
 * Built-in starter groups. Each seed is a generic description of the topic (subject words),
 * embedded once at install to give the group an initial centroid for clustering, naming and
 * search. Seeds do not drive assignment: the trained head does (src/classify/head.json).
 * Seeds never name brands or sites and never mimic page titles: site knowledge belongs in rules.ts.
 */
export interface StarterGroup {
  id: string;
  name: string;
  /** Hues spaced evenly round the wheel (OKLCH L 0.60, C 0.12), so every group stays distinguishable. The on-demand groups fill the gaps between them (L 0.55-0.65, C 0.09-0.15). */
  color: string;
  icon: string;
  seeds: string[];
  /**
   * Not created at install: the group appears later, when the user picks it in the interests step or when two
   * tabs need it. Its seeds still give it a centroid (buildTrainedGroup); the trained head decides assignment.
   */
  onDemand?: boolean;
}

